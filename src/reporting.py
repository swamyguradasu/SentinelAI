"""
Reporting and Data Export Module for SentinelAI.
Handles telemetry summary aggregation, audit trail generation,
and filtered CSV exports.
"""
import io
from typing import Any, Dict, List, Optional
import numpy as np
import pandas as pd


def generate_fleet_summary_metrics(df: pd.DataFrame) -> Dict[str, Any]:
    """
    Computes high-level fleet statistics.
    """
    if df.empty:
        return {
            "total_engines": 0,
            "total_observations": 0,
            "min_cycle": 0,
            "max_cycle": 0,
            "avg_cycles_per_engine": 0.0,
            "active_sensors_count": 0,
        }

    sensors = [c for c in df.columns if c.startswith("sensor_")]
    cycles_per_eng = df.groupby("engine_id")["cycle"].max()

    return {
        "total_engines": int(df["engine_id"].nunique()),
        "total_observations": int(len(df)),
        "min_cycle": int(cycles_per_eng.min()),
        "max_cycle": int(cycles_per_eng.max()),
        "avg_cycles_per_engine": float(round(cycles_per_eng.mean(), 1)),
        "active_sensors_count": len(sensors),
    }


def filter_anomaly_records(
    df: pd.DataFrame,
    engine_id: Optional[int] = None,
    min_score: float = 0.0,
    health_status: Optional[str] = None,
    detection_method: str = "Any",  # "Any", "Isolation Forest", "Quantile Baseline", "Both"
    search_keyword: Optional[str] = None,
) -> pd.DataFrame:
    """
    Filters telemetry and anomaly log by multiple interactive criteria.
    """
    if df.empty:
        return df.copy()

    filtered = df.copy()

    if engine_id is not None and engine_id != "All":
        filtered = filtered[filtered["engine_id"] == int(engine_id)]

    if "anomaly_score" in filtered.columns:
        filtered = filtered[filtered["anomaly_score"] >= min_score]

    if health_status and health_status != "All" and "health_status" in filtered.columns:
        filtered = filtered[filtered["health_status"] == health_status]

    if detection_method == "Isolation Forest" and "is_anomaly_if" in filtered.columns:
        filtered = filtered[filtered["is_anomaly_if"] == 1]
    elif detection_method == "Quantile Baseline" and "is_anomaly_base" in filtered.columns:
        filtered = filtered[filtered["is_anomaly_base"] == 1]
    elif detection_method == "Both" and "is_anomaly_if" in filtered.columns and "is_anomaly_base" in filtered.columns:
        filtered = filtered[(filtered["is_anomaly_if"] == 1) & (filtered["is_anomaly_base"] == 1)]

    if search_keyword and "triggering_sensors" in filtered.columns:
        kw = search_keyword.strip().lower()
        if kw:
            filtered = filtered[
                filtered["triggering_sensors"].astype(str).str.lower().str.contains(kw)
            ]

    return filtered


def export_dataframe_to_csv_bytes(df: pd.DataFrame) -> bytes:
    """
    Converts a pandas DataFrame into utf-8 encoded CSV bytes for Streamlit download buttons.
    """
    buffer = io.StringIO()
    df.to_csv(buffer, index=False)
    return buffer.getvalue().encode("utf-8")


def generate_audit_report_markdown(
    dataset_name: str,
    fleet_metrics: Dict[str, Any],
    model_eval: Optional[Dict[str, Any]] = None,
    health_counts: Optional[Dict[str, int]] = None,
) -> str:
    """
    Creates a comprehensive Markdown audit report suitable for export or reporting.
    """
    md = [
        f"# SentinelAI Operational Telemetry & Anomaly Report",
        f"**Dataset**: {dataset_name}",
        f"**Engines Monitored**: {fleet_metrics.get('total_engines', 0)}",
        f"**Total Telemetry Cycles Processed**: {fleet_metrics.get('total_observations', 0):,}",
        "",
        "## Fleet Health Breakdown",
    ]
    if health_counts:
        for status, count in health_counts.items():
            md.append(f"- **{status}**: {count} units")
    else:
        md.append("- No health data processed.")

    if model_eval:
        md.extend([
            "",
            "## Model Evaluation Summary",
            f"- **Precision**: {model_eval.get('precision', 0.0):.4f}",
            f"- **Recall**: {model_eval.get('recall', 0.0):.4f}",
            f"- **F1 Score**: {model_eval.get('f1_score', 0.0):.4f}",
            f"- **Accuracy**: {model_eval.get('accuracy', 0.0):.4f}",
        ])
        if model_eval.get("warnings"):
            md.append("\n**Evaluation Warnings:**")
            for w in model_eval["warnings"]:
                md.append(f"- *{w}*")

    md.extend([
        "",
        "---",
        "*Report auto-generated by SentinelAI Predictive Maintenance Suite.*",
    ])
    return "\n".join(md)
